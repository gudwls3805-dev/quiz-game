while True:
    # ① 메뉴 출력 (반복마다 매번 보여줌)
    print("========================================")
    print("         🎯 나만의 퀴즈 게임 🎯")
    print("========================================")
    print("1. 퀴즈 풀기")
    print("2. 퀴즈 추가")
    print("3. 퀴즈 목록")
    print("4. 점수 확인")
    print("5. 종료")
    print("========================================")

    # ② 입력받기
    choice = input("선택: ").strip()

    # ③ 고른 번호의 '행동'만 (여기선 메뉴를 다시 찍지 않음)
    if choice == "1":
        print("퀴즈 풀기 (준비 중)")
    elif choice == "2":
        print("퀴즈 추가 (준비 중)")
    elif choice == "3":
        print("퀴즈 목록 (준비 중)")
    elif choice == "4":
        print("점수 확인 (준비 중)")
    elif choice == "5":
        print("종료합니다")
        break
    else:
        print("⚠️ 잘못된 입력입니다. 1-5 사이 숫자를 입력하세요.")